const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const root=fs.existsSync(path.join(__dirname,'../roda'))?'../roda':'..';
const api=require(path.join(__dirname,root,'js/shot-planning.js'));
const history=require(path.join(__dirname,root,'js/planning-history.js'));
const state={scenes:[{id:'a',number:1,shots:[{id:'p1',durMin:10},{id:'p2',durMin:20},{id:'p3',durMin:30}]},{id:'b',number:2,shots:[{id:'p4',durMin:15}]}]};
const day={id:'day',callTime:'08:00',sceneIds:['a','b'],times:{a:30,b:135},durations:{a:60,b:30},blocks:[{id:'arrival',startMin:0,durMin:30},{id:'lunch',startMin:90,durMin:45}]};
const original=structuredClone({state,day});
assert.deepEqual(api.sceneRows(state,day,'a').map(r=>[r.start,r.dur]),[[30,10],[40,20],[60,30]]);
assert.deepEqual(api.sceneRows(state,day,'b').map(r=>r.dur),[30]);
assert.deepEqual({state,day},original,'viewing must not mutate data');
const h=history.create({days:[day]});
assert.equal(api.reorder(state,day,'a','a|p3','a|p1'),true);h.record([day]);
assert.deepEqual(api.sceneRows(state,day,'a').map(r=>[r.shotId,r.start,r.dur]),[['p3',30,30],['p1',60,10],['p2',70,20]]);
assert.deepEqual(day.times,original.day.times);assert.deepEqual(state,original.state);
assert.equal(h.undo([day],['a','b']).ok,true);assert.deepEqual(day,original.day);
assert.equal(h.redo([day],['a','b']).ok,true);
api.duration(state,day,'a','a|p1',25);h.record([day]);
assert.equal(day.durations.a,75);assert.equal(day.times.b,150);assert.equal(day.blocks[1].startMin,105);assert.equal(day.blocks[0].startMin,0);
assert.equal(h.undo([day],['a','b']).ok,true);assert.equal(day.times.b,135);assert.equal(day.durations.a,60);
assert.equal(h.redo([day],['a','b']).ok,true);
const saved=JSON.parse(JSON.stringify(day));assert.deepEqual(api.rows(state,saved),api.rows(state,day));
assert.throws(()=>api.duration(state,day,'a','a|p1',0));assert.deepEqual(day,saved);
day.times.b=40;const overlap=structuredClone(day);assert.throws(()=>api.duration(state,day,'a','a|p1',10));assert.deepEqual(day,overlap);
const short=structuredClone(original.day);short.durations.a=2;assert.equal(api.sceneRows(state,short,'a')[0].kind,'scene');
state.scenes[1].shots.push({id:'insert',shootingSceneId:'a',durMin:10});
const batch=api.sceneRows(state,original.day,'a');assert.equal(batch.length,4);assert.equal(batch.at(-1).ownerId,'b');assert.equal(batch.reduce((sum,r)=>sum+r.dur,0),60);
state.scenes[0].shots.splice(1,1);assert.equal(api.sceneRows(state,saved,'a').some(r=>r.shotId==='p2'),false);
console.log('Shot planning: projection, batches, reorder, duration, undo/redo, persistence and atomic rejection passed.');

const swap=require(path.join(__dirname,root,'js/day-swap.js'));
const first=structuredClone(saved),second={id:'other',callTime:'08:00',sceneIds:['z'],times:{z:0},durations:{z:20},blocks:[]};
assert.equal(swap.swapScenesBetweenDays(first,'a',second,'z'),true);
assert.deepEqual(second.shotPlanning.a,saved.shotPlanning.a);assert.equal(first.shotPlanning.a,undefined);
assert.equal(swap.swapScenesBetweenDays(second,'a',first,'z'),true);assert.deepEqual(first.shotPlanning.a,saved.shotPlanning.a);
console.log('Shot plans follow scene swaps across days.');
